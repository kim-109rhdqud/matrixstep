def mpow(A, n):
    P = ident(len(A))
    for _ in range(n):
        P = matmul(P, A)
    return P


def inv2(A):
    d = det2(A)
    return [[A[1][1] / d, -A[0][1] / d], [-A[1][0] / d, A[0][0] / d]]


