{box(line("Aⁿ = PDⁿP⁻¹ = 1/3 ·"), mx_text([["2ⁿ + 2·5ⁿ", "−2ⁿ + 5ⁿ"], ["−2·2ⁿ + 2·5ⁿ", "2·2ⁿ + 5ⁿ"]]))}
